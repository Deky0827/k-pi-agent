// Pin the data home to the directory used by the previous "Pi Desktop" builds.
// Without this, renaming the app would move userData (payloads, logs and the
// single-instance lock) to "%APPDATA%\\k-pi-agent" and re-copy the whole seed.
// Pinning keeps an in-place upgrade transparent: already-downloaded Pi Web
// payloads and the Node runtime keep working, and sessions continue untouched
// (Pi agent data itself lives in ~/.pi/agent and is never touched by installs).
// K_AGENT_DATA_DIR overrides the pin entirely — used for isolated test runs.
app.setPath(
  "userData",
  process.env.K_AGENT_DATA_DIR ?? path.join(app.getPath("appData"), "pi-desktop")
);

