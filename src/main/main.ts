let mainWindow: BrowserWindow | undefined;
let settingsWindow: BrowserWindow | undefined;
let tray: Tray | undefined;
let quitting = false;
let allowQuit = false;
let shutdownTask: Promise<void> | undefined;
let serviceRecoveryOpen = false;
let hideHintShown = false;
let lastThemeMode: KAgentSettings["theme"]["mode"] = "system";
const runtime = new RuntimeManager();
const piWeb = new PiWebManager();
const service = new PiWebService();
const updateManager = new UpdateManager(runtime, piWeb);

service.onUnexpectedExit((reason) => { void recoverPiWebService(reason); });

function showMainWindow(): void {
  if (!mainWindow) return;
  if (mainWindow.isMinimized()) mainWindow.restore();
  mainWindow.show();
  mainWindow.focus();
}

function openSettingsWindow(): void {
  if (settingsWindow && !settingsWindow.isDestroyed()) {
    settingsWindow.show();
    settingsWindow.focus();
    return;
  }
  settingsWindow = new BrowserWindow({
    width: 760,
    height: 640,
    show: false,
    title: "K pi agent 设置",
    minimizable: false,
    maximizable: false,
    fullscreenable: false,
    autoHideMenuBar: true,
    backgroundColor: "#17171d",
    webPreferences: {
      preload: path.join(import.meta.dirname, "../preload/index.cjs"),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true
    }
  });
  settingsWindow.on("closed", () => { settingsWindow = undefined; });
  void settingsWindow.loadFile(path.join(settingsUiRoot(), "index.html"));
  settingsWindow.once("ready-to-show", () => settingsWindow?.show());
}

function updateTray(): void {
  if (!tray || tray.isDestroyed()) return;
  tray.setToolTip("K pi agent — 双击打开，服务在后台运行");
  tray.setContextMenu(Menu.buildFromTemplate([
    { label: "显示主界面", click: () => showMainWindow() },
    { label: "设置…", click: () => openSettingsWindow() },
    { type: "separator" },
    {
      label: "桌宠",
      type: "checkbox",
      checked: trayPetChecked,
      click: async (item) => {
        if (item.checked) {
          const current = await getSettings();
          if (!current.pet.activePetId) {
            const pets = await listPets();
            if (!pets.length) {
              trayPetChecked = false;
              updateTray();
              return; // no pet resources installed yet
            }
            await setSettings({ pet: { activePetId: pets[0].id, enabled: true } });
            return;
          }
        }
        await setSettings({ pet: { enabled: item.checked } });
      }
    },
    { type: "separator" },
    {
      label: "退出 K pi agent",
      click: () => app.quit()
    }
  ]));
}

let trayPetChecked = false;

function createTray(): void {
  tray = new Tray(nativeImage.createFromBuffer(Buffer.from(TRAY_ICON_BASE64, "base64")));
  tray.on("click", () => showMainWindow());
  tray.on("double-click", () => showMainWindow());
  updateTray();
}

function createWindow(): BrowserWindow {
  const window = new BrowserWindow({
    width: 1440,
    height: 960,
    minWidth: 980,
    minHeight: 640,
    show: false,
    title: "K pi agent",
    webPreferences: {
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
      preload: path.join(import.meta.dirname, "../preload/index.cjs")
    }
  });
  window.webContents.setWindowOpenHandler(({ url }) => {
    if (/^https?:\/\//i.test(url)) void shell.openExternal(url);
    return { action: "deny" };
  });
  window.webContents.on("will-navigate", (event, url) => {
    if (!url.startsWith(PI_WEB_URL)) {
      event.preventDefault();
      if (/^https?:\/\//i.test(url)) void shell.openExternal(url);
    }
  });
  window.webContents.on("did-finish-load", () => {
    if (mainWindow) void applyAppearance(mainWindow, currentSettings);
  });
  window.once("ready-to-show", () => window.show());
  window.on("close", (event) => {
    if (!quitting) {
      // Minimize to tray instead of quitting: the Pi Web server (and any
      // running agent sessions) keep working in the background.
      event.preventDefault();
      window.hide();
      if (!hideHintShown) {
        hideHintShown = true;
        try {
          tray?.displayBalloon({
            iconType: "info",
            title: "K pi agent 仍在后台运行",
            content: "会话不会被关闭。双击托盘图标可重新打开窗口；右键托盘图标可选择退出。"
          });
        } catch {
          // Balloons are Windows-only niceties; ignore failures.
        }
      }
    }
  });
  return window;
}

let currentSettings: KAgentSettings = {
  pet: { enabled: false, activePetId: null, scale: 1.2, x: null, y: null },
  theme: { mode: "system", activeThemeId: null },
  ui: { zoom: 1, customCss: "" },
  removedBundledPets: []
};

async function applyLiveSettings(settings: KAgentSettings, previous: KAgentSettings): Promise<void> {
  currentSettings = settings;
  if (mainWindow && !mainWindow.isDestroyed()) {
    await applyAppearance(mainWindow, settings);
    if (settings.theme.mode !== previous.theme.mode) {
      lastThemeMode = settings.theme.mode;
      await forceThemeMode(mainWindow, settings.theme.mode);
    }
  }
  trayPetChecked = settings.pet.enabled;
  updateTray();
  await refreshPet();
  settingsWindow?.webContents.send("settings:changed");
}

function buildApplicationMenu(): void {
  Menu.setApplicationMenu(Menu.buildFromTemplate([
    {
      label: "K pi agent",
      submenu: [
        { label: "设置…", accelerator: "CmdOrCtrl+,", click: () => openSettingsWindow() },
        { type: "separator" },
        { label: "退出", role: "quit" }
      ]
    },
    { label: "编辑", role: "editMenu" },
    { label: "视图", role: "viewMenu" },
    { label: "窗口", role: "windowMenu" }
  ]));
}

async function startup(): Promise<void> {
  if (quitting) return;
  await updateManager.recoverInterruptedInstall();
  if (quitting) return;
  const network = await resolveNetworkEnvironment();
  await configureElectronNetwork(network);
  if (quitting) return;
  const [runtimeInfo, piWebInfo] = await Promise.all([runtime.current(), piWeb.current()]);
  if (quitting) return;

  registerPetIpc();
  registerSettingsIpc({
    onResourceChanged: () => refreshPet()
  });
  onSettingsChanged((settings) => {
    const previous = currentSettings;
    void applyLiveSettings(settings, previous);
  });
  await syncBundledPets();
  if (quitting) return;
  currentSettings = await getSettings();
  lastThemeMode = currentSettings.theme.mode;
  const settingsWarning = getSettingsWarning();
  if (settingsWarning) {
    await dialog.showMessageBox({
      type: "warning",
      title: "设置文件已备份",
      message: "原有设置无法读取，已加载默认设置。",
      detail: settingsWarning,
      buttons: ["确定"]
    });
  }
  if (quitting) return;
  buildApplicationMenu();
  createTray();
  await service.start(runtimeInfo, piWebInfo, network);
  if (quitting) return;
  mainWindow = createWindow();
  await mainWindow.loadURL(PI_WEB_URL);
  await applyAppearance(mainWindow, currentSettings);
  await forceThemeMode(mainWindow, currentSettings.theme.mode);
  await refreshPet();
  void updateManager.checkAndOffer();
}

async function shutdown(): Promise<void> {
  if (shutdownTask) return shutdownTask;
  quitting = true;
  shutdownTask = (async () => {
    tray?.destroy();
    tray = undefined;
    try {
      await service.stop();
    } catch (error) {
      await dialog.showMessageBox({
        type: "warning",
        title: "Pi Web 服务停止异常",
        message: error instanceof Error ? error.message : String(error),
        detail: "请检查任务管理器中由 K pi agent 启动的 Node 进程。"
      });
    } finally {
      if (mainWindow && !mainWindow.isDestroyed()) mainWindow.destroy();
      if (settingsWindow && !settingsWindow.isDestroyed()) settingsWindow.destroy();
      allowQuit = true;
      app.quit();
    }
  })();
  return shutdownTask;
}

async function recoverPiWebService(reason: string): Promise<void> {
  if (serviceRecoveryOpen || quitting) return;
  serviceRecoveryOpen = true;
  showMainWindow();
  let failure = reason;
  try {
    while (!quitting) {
      const options = {
        type: "error" as const,
        title: "Pi Web 服务已停止",
        message: failure,
        detail: `查看日志：${path.join(app.getPath("logs"), "pi-web.log")}`,
        buttons: ["重启 Pi Web 服务", "退出 K pi agent"],
        defaultId: 0,
        cancelId: 1
      };
      const { response } = mainWindow && !mainWindow.isDestroyed()
        ? await dialog.showMessageBox(mainWindow, options)
        : await dialog.showMessageBox(options);
      if (response !== 0) {
        void shutdown();
        return;
      }
      try {
        const [runtimeInfo, piWebInfo, network] = await Promise.all([
          runtime.current(), piWeb.current(), resolveNetworkEnvironment()
        ]);
        await service.start(runtimeInfo, piWebInfo, network);
        if (mainWindow && !mainWindow.isDestroyed()) await mainWindow.loadURL(PI_WEB_URL);
        return;
      } catch (error) {
        failure = `重启失败：${error instanceof Error ? error.message : String(error)}`;
      }
    }
  } finally {
    serviceRecoveryOpen = false;
  }
}

if (!app.requestSingleInstanceLock()) {
  app.quit();
} else {
  app.on("second-instance", () => {
    showMainWindow();
  });
  app.whenReady().then(startup).catch(async (error: unknown) => {
    if (quitting) return;
    await dialog.showMessageBox({
      type: "error",
      title: "K pi agent could not start",
      message: error instanceof Error ? error.message : String(error),
      detail: "No unknown process was terminated. Check whether port 30141 is in use, then try again."
    });
    await shutdown();
  });
  app.on("window-all-closed", () => { void shutdown(); });
  app.on("before-quit", (event) => {
    quitting = true;
    if (allowQuit) return;
    event.preventDefault();
    void shutdown();
  });
}
